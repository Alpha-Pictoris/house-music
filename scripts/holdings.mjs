export function renderHoldingRow(record) {
  return `<tr class="govuk-table__row" data-record="${record.reference} ${record.search}" data-title="${record.title}">
    <td class="govuk-table__cell"><a class="govuk-link" href="/records/${record.slug}/">${record.title}</a><p class="govuk-body-s record-description">${record.description}</p></td>
    <td class="govuk-table__cell"><span class="catalogue-ref">${record.reference}</span></td>
    <td class="govuk-table__cell">${record.year}</td>
  </tr>`;
}

function renderTable({ caption, headings, rows }) {
  const columns = headings.map(heading => `<th class="govuk-table__header" scope="col">${heading}</th>`);
  const entries = rows.map(([label, ...values]) => {
    const cells = values.map(value => `<td class="govuk-table__cell">${value}</td>`);
    return `<tr class="govuk-table__row"><th class="govuk-table__header" scope="row">${label}</th>${cells.join("")}</tr>`;
  });
  return `<table class="govuk-table">
    <caption class="govuk-table__caption govuk-table__caption--m">${caption}</caption>
    <thead class="govuk-table__head"><tr class="govuk-table__row">${columns.join("")}</tr></thead>
    <tbody class="govuk-table__body">${entries.join("\n")}</tbody>
  </table>`;
}

